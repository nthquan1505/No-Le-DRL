def _parse_yaml_value(val: str, depth: int = 0):
    """Parse a scalar YAML value string."""
    s = val.strip()
    if not s:
        return None
    # boolean
    if s in ("true", "yes", "on"):
        return True
    if s in ("false", "no", "off"):
        return False
    # null
    if s in ("null", "~", ""):
        return None
    # quoted string
    if (s.startswith('"') and s.endswith('"')) or (s.startswith("'") and s.endswith("'")):
        inner = s[1:-1]
        inner = inner.replace('\\"', '"').replace("\\'", "'")
        return inner
    # integer
    try:
        return int(s)
    except ValueError:
        pass
    # float
    try:
        return float(s)
    except ValueError:
        pass
    return s


def _split_respecting_brackets(s: str):
    """Split comma-separated list respecting [], {} nesting."""
    parts = []
    depth = 0
    cur = []
    for ch in s:
        if ch in ('[', '{'):
            depth += 1
            cur.append(ch)
        elif ch in (']', '}'):
            depth -= 1
            cur.append(ch)
        elif ch == ',' and depth == 0:
            parts.append(''.join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if cur:
        parts.append(''.join(cur).strip())
    return parts


def _parse_inline_list(s: str):
    """Parse inline YAML list: [a, b, c]"""
    s = s.strip()
    if s.startswith('[') and s.endswith(']'):
        inner = s[1:-1].strip()
        if not inner:
            return []
        parts = _split_respecting_brackets(inner)
        return [_parse_yaml_value(p.strip()) for p in parts]
    return [_parse_yaml_value(s)]


def _parse_inline_dict(s: str):
    """Parse inline YAML dict: {k: v, k2: v2}"""
    s = s.strip()
    if s.startswith('{') and s.endswith('}'):
        inner = s[1:-1].strip()
        if not inner:
            return {}
        result = {}
        parts = _split_respecting_brackets(inner)
        for part in parts:
            if ':' in part:
                k, _, v = part.partition(':')
                result[_parse_yaml_value(k.strip())] = _parse_yaml_value(v.strip())
            else:
                result[_parse_yaml_value(part.strip())] = None
        return result
    return {}


def _parse_inline(s: str):
    """Dispatch inline value parsing."""
    s = s.strip()
    if s.startswith('['):
        return _parse_inline_list(s)
    if s.startswith('{'):
        return _parse_inline_dict(s)
    return _parse_yaml_value(s)


