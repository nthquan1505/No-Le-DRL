            content = line.strip()
            
            # Block scalar (|, >)
            if content.endswith(' |') or content.endswith(' >') or content == '|' or content == '>':
                # multi-line block value follows
                block_char = content[-1]
                # collect lines at greater indent
                key_part = content[:-1].rstrip()
                block_lines = []
